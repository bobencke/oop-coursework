    public void inserirTexto(){
        String texto = jTextField1.getText();
        if (!texto.isEmpty()) {
            jTextArea1.append(texto + "\n");
            jTextField1.setText("");
        }
    }
    
    private void abrirJanelaBusca() {
        new Localizar(historicoBuscas, jTextArea1);
    }

