    public Localizar(List<String> historico, javax.swing.JTextArea textoArea) {
        initComponents();
        setLocationRelativeTo(null);
        setVisible(true);
        
        jComboBox1.setEditable(true);
        
        modeloCombo = new DefaultComboBoxModel<>();
        for (String termo : historico) {
            modeloCombo.addElement(termo);
        }
        jComboBox1.setModel(modeloCombo);

        jButton1.addActionListener(e -> {
        String termo = (String) jComboBox1.getEditor().getItem();
        if (!termo.trim().isEmpty()) {
            historico.add(termo);
            modeloCombo.addElement(termo); // atualiza dropdown
            
           String conteudo = textoArea.getText().toLowerCase();
                if (conteudo.contains(termo.toLowerCase())) {
                    JOptionPane.showMessageDialog(this, "Termo encontrado!", "Resultado", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Termo não encontrado.", "Resultado", JOptionPane.WARNING_MESSAGE);
                }
        }
    });
        
        jButton2.addActionListener(e -> dispose());
        
    }

