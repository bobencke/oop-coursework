    public void proximaPagina(Detento d){
        
        boolean intersexo;
        
        String respostaDeficiencia = deficienciaNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (deficienciaTxt.getText().trim().isEmpty() ? "Não" : deficienciaTxt.getText());
        d.setDeficiencia(respostaDeficiencia);
        
        String respostaIntolerancia = intoleranciaNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (intoleranciaAlimentarTxt.getText().trim().isEmpty() ? "Não" : intoleranciaAlimentarTxt.getText());
        d.setIntoleranciaAlimentar(respostaIntolerancia);
        
        String respostaCirurgia = cirurgiaNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (cirurgiasTxt.getText().trim().isEmpty() ? "Não" : cirurgiasTxt.getText());
        d.setCirurgias(respostaCirurgia);
        
        List<String> condicoesCronicas = new ArrayList<>();
        if (hipertensaoRB.isSelected()) condicoesCronicas.add("Hipertensão");
        if (diabetesRB.isSelected()) condicoesCronicas.add("Diabetes");
        if (hivRB.isSelected()) condicoesCronicas.add("HIV");
        d.setCondicoesCronicas(condicoesCronicas.isEmpty() ? "Nenhuma" : String.join(", ", condicoesCronicas));
        
        List<String> doencasInfecciosas = new ArrayList<>();
        if (sifilisRB.isSelected()) doencasInfecciosas.add("Sífilis");
        if (hpvRB.isSelected()) doencasInfecciosas.add("HPV");
        if (tuberculoseRB.isSelected()) doencasInfecciosas.add("Tuberculose");
        d.setDoencasInfecciosas(doencasInfecciosas.isEmpty() ? "Nenhuma" : String.join(", ", doencasInfecciosas));
        
        d.setDoencaDePele(doencaPeleTxt.getText().trim().isEmpty() ? "Não" : doencaPeleTxt.getText());
        
        String respostAutoimune = autoimuneNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (autoimuneTxt.getText().trim().isEmpty() ? "Não" : autoimuneTxt.getText());
        d.setAutoimune(respostAutoimune);
        
        String respostaHepatiteB = hepatiteBNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (hepatiteBTxt.getText().trim().isEmpty() ? "Não" : hepatiteBTxt.getText());
        d.setHepatiteB(respostaHepatiteB);
        
        String respostaHepatiteC = hepatiteCNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (hepatiteCTxt.getText().trim().isEmpty() ? "Não" : hepatiteCTxt.getText());
        d.setHepatiteC(respostaHepatiteC);
        
        String respostaMedicamento = medicamentoNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (medicamentoTxt.getText().trim().isEmpty() ? "Não" : medicamentoTxt.getText());
        d.setMedicamentoContinuo(respostaMedicamento);
        
        String respostaTipo = tipoNaoSabe.isSelected() 
        ? "Não sabe responder" 
        : (tipoSanguineoTxt.getText().trim());
        d.setTipoSanguineo(respostaTipo);
        
        dispose();
        
        if(d.getSexoBiologico() == "Feminino"){
            CadastroSaudeMulher csm = new CadastroSaudeMulher(d);
            csm.setTitle("Saúde da Mulher");
            csm.setLocationRelativeTo(null);
            csm.setVisible(true);
        }
        else if(d.getSexoBiologico() == "Masculino"){
            CadastroSaudeHomem csh = new CadastroSaudeHomem(d);
            csh.setTitle("Saúde do Homem");
            csh.setLocationRelativeTo(null);
            csh.setVisible(true);
        }
        else {
            intersexo = true;
            
            CadastroSaudeMulher csm = new CadastroSaudeMulher(d, intersexo);
            csm.setTitle("Saúde da Mulher");
            csm.setLocationRelativeTo(null);
            csm.setVisible(true);
        }
        
        
        
    }

