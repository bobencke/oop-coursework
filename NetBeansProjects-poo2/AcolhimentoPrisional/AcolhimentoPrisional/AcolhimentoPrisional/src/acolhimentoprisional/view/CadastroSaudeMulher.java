    public void proximaPagina(Detento d){
        
        String respostaGestacao = gestacaoNaoSabe.isSelected() 
        ? "0"
        : (gestacaoTxt.getText().trim().isEmpty() ? "0" : gestacaoTxt.getText());
        d.setIdadeGestacional(Integer.parseInt(respostaGestacao));
        
        d.setMetodoContraceptivo(contraceptivoTxt.getText().trim().isEmpty() ? "Não" : contraceptivoTxt.getText());
        
        d.setExamePreventivo(papanicolauTxt.getText().trim().isEmpty() ? "Não" : papanicolauTxt.getText());
        
        d.setContinuidadeContraceptivo(contraceptivoSimRB.isSelected());
        
        d.setConsultaExamePreventivo(preventivoSimRB.isSelected());
        
        d.setEncaminhamentPreNatal(preNatalSimRB.isSelected());
        
        dispose();
        
        CadastroSaudeMental csme = new CadastroSaudeMental(d);
        csme.setTitle("Saúde Mental e Uso de Substâncias");
        csme.setLocationRelativeTo(null);
        csme.setVisible(true);
        
    }
    
