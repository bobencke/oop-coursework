    public void proximaPagina(Detento d){
        
        d.setRecebeuVacinaCovid(vacinaCovidRB.isSelected());
        
        d.setRecebeuVacinaInfluenza(vacinaInfluenzaRB.isSelected());
        
        d.setRecebeuVacinaTetano(vacinaTetanoRB.isSelected());
        
        d.setRecebeuVacinaHepatiteB(vacinaHepatiteB.isSelected());
        
        List<String> vacinasAOfertar = new ArrayList<>();
        if (hepatiteBRB.isSelected()) vacinasAOfertar.add("Hepatite B");
        if (covidRB.isSelected()) vacinasAOfertar.add("Covid-19");
        if (influenzaRB.isSelected()) vacinasAOfertar.add("Influenza");
        if (febreAmarelaRB.isSelected()) vacinasAOfertar.add("Febre Amarela");
        if (dtRB.isSelected()) vacinasAOfertar.add("Dupla Adulto (dT)");
        if (srcRB.isSelected()) vacinasAOfertar.add("Tríplice Viral (SRC)");
        if (!outraVacinaTxt.getText().trim().isEmpty()) {
            vacinasAOfertar.add(outraVacinaTxt.getText().trim());
        }
        d.setVacinasAOfertar(vacinasAOfertar.isEmpty() ? "Nenhum" : String.join(", ", vacinasAOfertar));
        
        d.setCopiaCarteiraVacinacao(ofertarCopiaCarteiraVacinacaoRB.isSelected());
        
        dispose();
        
        CadastroPrimeiroAtendimento csv = new CadastroPrimeiroAtendimento(d);
        csv.setTitle("Primeiro Atendimento Clínico");
        csv.setLocationRelativeTo(null);
        csv.setVisible(true);
        
    }

