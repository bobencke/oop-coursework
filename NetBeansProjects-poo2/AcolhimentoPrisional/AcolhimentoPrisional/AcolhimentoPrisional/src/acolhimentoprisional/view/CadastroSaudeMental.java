    public void proximaPagina(Detento d){
        
        d.setVinculoCAPS(vinculoCapsTxt.getText().trim().isEmpty() ? "Não" : vinculoCapsTxt.getText());
        
        List<String> transtornosMentais = new ArrayList<>();
        if (ansiedadeRB.isSelected()) transtornosMentais.add("Ansiedade");
        if (depressaoRB.isSelected()) transtornosMentais.add("Depressão");
        if (bipolaridadeRB.isSelected()) transtornosMentais.add("Bipolaridade");
        if (esquizofreniaRB.isSelected()) transtornosMentais.add("Esquizofrenia");
        if (autismoRB.isSelected()) transtornosMentais.add("Autismo");
        if (!outroTranstornoTxt.getText().trim().isEmpty()) {
            transtornosMentais.add(outroTranstornoTxt.getText().trim());
        }
        d.setTranstornosMentais(transtornosMentais.isEmpty() ? "Nenhum" : String.join(", ", transtornosMentais));
        
        d.setAcompanhamentoSaudeMental(acompanhamentoSaudeMentalTxt.getText().trim().isEmpty() ? "Não" : acompanhamentoSaudeMentalTxt.getText());
        
        List<String> usoDeDrogas = new ArrayList<>();
        if (alcoolRB.isSelected()) usoDeDrogas.add("Álcool");
        if (cigarroRB.isSelected()) usoDeDrogas.add("Cigarro");
        if (maconhaRB.isSelected()) usoDeDrogas.add("Maconha");
        if (crackRB.isSelected()) usoDeDrogas.add("Crack");
        if (cocainaRB.isSelected()) usoDeDrogas.add("Cocaína");
        if (anfetaminasRB.isSelected()) usoDeDrogas.add("Anfetamina");
        if (drogaKRB.isSelected()) usoDeDrogas.add("Drogas K");
        if (!outrasDrogasTxt.getText().trim().isEmpty()) {
            usoDeDrogas.add(outrasDrogasTxt.getText().trim());
        }
        d.setUsoDrogas(usoDeDrogas.isEmpty() ? "Nenhum" : String.join(", ", usoDeDrogas));
        
        d.setRealizouTratamentoParaUso(tratamentoUsoTxt.getText().trim().isEmpty() ? "Não" : tratamentoUsoTxt.getText());
        
        d.setDesejaRealizarTratamentoParaUso(gostariaTratamentoUsoTxt.getText().trim().isEmpty() ? "Não" : gostariaTratamentoUsoTxt.getText());
        
        d.setConsultaPsiciologia(consultaPsicologiaRB.isSelected());
        
        d.setConsultaPsiquiatria(consultaPsiquiatriaRB.isSelected());
        
        d.setEncaminhamentoRenovacaoReceita(encaminhamentoRenovacaoReceitaRB.isSelected());
        
        d.setEncaminhamentoGrupoDeApoio(encaminhamentoGrupoApoioRB.isSelected());
        
        dispose();
        
        CadastroSituacaoVacinal csv = new CadastroSituacaoVacinal(d);
        csv.setTitle("Situação Vacinal");
        csv.setLocationRelativeTo(null);
        csv.setVisible(true);
        
    }

