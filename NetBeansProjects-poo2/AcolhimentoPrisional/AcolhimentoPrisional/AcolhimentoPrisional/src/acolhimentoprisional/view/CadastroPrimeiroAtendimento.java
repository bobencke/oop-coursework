    public void proximaPagina(Detento d){
        
        d.setPeso(Float.parseFloat(pesoTxt.getText()));
        
        d.setAltura(Float.parseFloat(alturaTxt.getText()));
        
        d.setImc(Float.parseFloat(imcTxt.getText()));
        
        d.setPa(paTxt.getText());
        
        d.setFc(Float.parseFloat(fcTxt.getText()));
        
        d.setSat(Float.parseFloat(satTxt.getText()));
        
        d.setTemp(Float.parseFloat(tempTxt.getText()));
        
        List<String> sintomas = new ArrayList<>();
        if (tosseRB.isSelected()) sintomas.add("Tosse");
        if (corizaRB.isSelected()) sintomas.add("Coriza");
        if (esiprrosRB.isSelected()) sintomas.add("Espirros");
        if (febreRB.isSelected()) sintomas.add("Febre");
        if (calafriosRB.isSelected()) sintomas.add("Calafrios");
        if (!outrosSintomasTxt.getText().trim().isEmpty()) {
            sintomas.add(outrosSintomasTxt.getText().trim());
        }
        d.setSintomas(sintomas.isEmpty() ? "Nenhum" : String.join(", ", sintomas));
        
        String dataSintomasStr = dataSintomasTxt.getText();
        SimpleDateFormat formatoIn = new SimpleDateFormat("dd/MM/yyyy");
        SimpleDateFormat formatoOut = new SimpleDateFormat("yyyy-MM-dd");
        try {
            Date dataSintomas = formatoIn.parse(dataSintomasStr);
            d.setDataSintomas(formatoOut.format(dataSintomas));
        } catch (ParseException ex) {
            Logger.getLogger(CadastroPrimeiroAtendimento.class.getName())
                  .log(Level.SEVERE, "Erro ao converter data de sintomas", ex);
        }
        
        d.setLesoes(localLesoesTxt.getText().trim().isEmpty() ? "Não" : localLesoesTxt.getText());
        
        d.setConduta(condutaTxt.getText());
        
        dispose();
        
        CadastroTestesRapidos ctr = new CadastroTestesRapidos(d);
        ctr.setTitle("Testes Rápidos");
        ctr.setLocationRelativeTo(null);
        ctr.setVisible(true);
        
    }

