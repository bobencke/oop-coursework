    public void proximaPagina(Detento d){
        
        d.setAnoExameCancerProstata(Integer.parseInt(exameProstataTxt.getText().trim().isEmpty() ? "0" : exameProstataTxt.getText()));
        
        d.setFamiliarHistoricoCancerProstata(historicoCancerProstataTxt.getText().trim().isEmpty() ? "Não" : historicoCancerProstataTxt.getText());
        
        d.setVasectomia(vasectomiaSimRB.isSelected());
        
        d.setParceiraGestante(parceiraGestanteSimRB.isSelected());
        
        d.setParticipacaoPreNatal(participacaoPreNatalSimRB.isSelected());
        
        d.setEncaminhamentoVasectomia(encaminhamentoVasectomiaRB.isSelected());
        
        d.setEncaminhamentoPreNetalParceira(encaminhamentoPreNatalParceiroRB.isSelected());
        
        dispose();
        
        CadastroSaudeMental csme = new CadastroSaudeMental(d);
        csme.setTitle("Saúde Mental e Uso de Substâncias");
        csme.setLocationRelativeTo(null);
        csme.setVisible(true);
        
    }

