    public void proximaPagina(Detento d){
        
        d.setEscolaridade(escolaridadeTxt.getSelectedItem().toString());
        d.setProfissao(profissaoTxt.getText());
        d.setBeneficioFamiliar(beneficioQualTxt.getText().trim().isEmpty() ? "Não" : beneficioQualTxt.getText());
        d.setQuantFilhos(Integer.parseInt(filhosQuantosTxt.getText().trim().isEmpty() ? "0" : filhosQuantosTxt.getText()));
        d.setQuantDependentes(Integer.parseInt(depenQuantosTxt.getText().trim().isEmpty() ? "0" : depenQuantosTxt.getText()));
        d.setEncaminhamentoNEEJA(ofertarNeejaSimRB.isSelected());
        d.setConversaAssitSocial(ofertarAssistSocialSimRB.isSelected());
        
        dispose();
        
        CadastroCondicoesDeSaude ccs = new CadastroCondicoesDeSaude(d);
        ccs.setTitle("Condições de Saúde");
        ccs.setLocationRelativeTo(null);
        ccs.setVisible(true);
        
    }

