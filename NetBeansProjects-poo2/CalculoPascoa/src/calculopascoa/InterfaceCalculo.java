    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        try{
            String input = jTextField1.getText();
            int anoDigitado = Integer.parseInt(input);
            int diaPascoa = calcularDiaPascoa(anoDigitado);
            int mesInt = calcularMesPascoa(anoDigitado);
            String mesPascoa = definirMes(mesInt);
            jTextField2.setText(String.valueOf(diaPascoa));
            jTextField3.setText(String.valueOf(mesPascoa));
        }catch(Exception e){
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Favor digitar números");
            jTextField1.setText("");
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

